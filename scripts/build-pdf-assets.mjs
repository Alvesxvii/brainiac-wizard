import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

const dist = path.resolve("node_modules/pdfjs-dist");
const worker = await build({
	entryPoints: [path.join(dist, "legacy/build/pdf.worker.mjs")],
	bundle: true,
	format: "esm",
	target: "es2021",
	minify: true,
	write: false,
	logLevel: "silent",
});

function encodeDirectory(directory, extensions) {
	return Object.fromEntries(
		fs.readdirSync(directory, { withFileTypes: true })
			.filter((entry) => entry.isFile() && extensions.some((extension) => entry.name.endsWith(extension)))
			.map((entry) => [entry.name, fs.readFileSync(path.join(directory, entry.name)).toString("base64")]),
	);
}

const assets = {
	worker: worker.outputFiles[0].text,
	cmaps: encodeDirectory(path.join(dist, "cmaps"), [".bcmap"]),
	standardFonts: encodeDirectory(path.join(dist, "standard_fonts"), [".pfb", ".ttf"]),
};

const output = `// Generated by scripts/build-pdf-assets.mjs. Do not edit or commit.\nexport const PDFJS_ASSETS: { worker: string; cmaps: Record<string, string>; standardFonts: Record<string, string> } = ${JSON.stringify(assets)};\n`;
fs.writeFileSync("src/pdfjs-assets.generated.ts", output);
